@TestOn('vm')
library;

import 'package:test/test.dart';
import 'package:yaml/yaml.dart';

import '../test_support/throughput_baseline_overrides.dart';

const _baselinePubspec = '''
name: event_sourcing
version: 0.5.0

environment:
  sdk: ^3.10.0

dependencies:
  canonical_json_jcs:
    path: ../canonical_json_jcs
  collection: ^1.19.0
  postgres: ^3.5.0
  sembast: ^3.7.3
  pinned_hosted:
    hosted: https://pub.dev
    version: ^2.0.0
  from_git:
    git:
      url: https://example.com/from_git.git
  flutter:
    sdk: flutter
  only_in_baseline: ^1.0.0

dev_dependencies:
  test: ^1.25.0
''';

const _currentLock = '''
# Generated by pub
packages:
  canonical_json_jcs:
    dependency: "direct main"
    description:
      path: "../canonical_json_jcs"
      relative: true
    source: path
    version: "1.0.0"
  collection:
    dependency: transitive
    description:
      name: collection
      sha256: "0000"
      url: "https://pub.dev"
    source: hosted
    version: "1.19.1"
  pinned_hosted:
    dependency: "direct main"
    description:
      name: pinned_hosted
      sha256: "0000"
      url: "https://pub.dev"
    source: hosted
    version: "2.3.4"
  postgres:
    dependency: "direct main"
    description:
      name: postgres
      sha256: "0000"
      url: "https://pub.dev"
    source: hosted
    version: "3.5.20"
  sembast:
    dependency: "direct main"
    description:
      name: sembast
      sha256: "0000"
      url: "https://pub.dev"
    source: hosted
    version: "3.8.11"
  test:
    dependency: "direct dev"
    description:
      name: test
      sha256: "0000"
      url: "https://pub.dev"
    source: hosted
    version: "1.31.0"
sdks:
  dart: ">=3.10.0 <4.0.0"
''';

void main() {
  // Verifies: EVS-DEV-chain-verification/T
  test('holds each hosted dependency the baseline shares with the current '
      'tree at the version the current tree resolved', () {
    final overrides = baselineDependencyOverrides(
      baselinePubspec: _baselinePubspec,
      currentLock: _currentLock,
    );
    expect(overrides.versions, <String, String>{
      'collection': '1.19.1',
      'pinned_hosted': '2.3.4',
      'postgres': '3.5.20',
      'sembast': '3.8.11',
    });
  });

  // Verifies: EVS-DEV-chain-verification/T
  test('the overrides file pins exactly those versions', () {
    final overrides = baselineDependencyOverrides(
      baselinePubspec: _baselinePubspec,
      currentLock: _currentLock,
    );
    final parsed = loadYaml(overrides.yaml) as YamlMap;
    final pinned = (parsed['dependency_overrides'] as YamlMap).map(
      (k, v) => MapEntry(k as String, v as String),
    );
    expect(pinned, overrides.versions);
    expect(parsed.keys, <Object>['dependency_overrides']);
  });

  test('leaves path, git and sdk dependencies, dev dependencies, and '
      'dependencies the current tree does not resolve, unpinned', () {
    final overrides = baselineDependencyOverrides(
      baselinePubspec: _baselinePubspec,
      currentLock: _currentLock,
    );
    for (final name in <String>[
      'canonical_json_jcs',
      'from_git',
      'flutter',
      'only_in_baseline',
      'test',
    ]) {
      expect(overrides.versions, isNot(contains(name)), reason: name);
    }
  });

  test('pins nothing when the baseline shares no hosted dependency', () {
    final overrides = baselineDependencyOverrides(
      baselinePubspec: 'name: x\ndependencies:\n  only_in_baseline: ^1.0.0\n',
      currentLock: _currentLock,
    );
    expect(overrides.versions, isEmpty);
    expect(
      (loadYaml(overrides.yaml) as YamlMap)['dependency_overrides'],
      anyOf(isNull, isEmpty),
    );
  });
}
